import assert from 'node:assert/strict'
import {writeFile} from 'node:fs/promises'
import {connect} from './cdp.mjs'

const base=process.env.TEST_BASE_URL??'http://127.0.0.1:4173'
const port=process.env.TEST_CDP_PORT??'9222'
const pages=await(await fetch('http://127.0.0.1:'+port+'/json')).json()
const c=await connect(pages.find(p=>p.url.startsWith('http://127.0.0.1')).webSocketDebuggerUrl)
await c.call('Runtime.enable');await c.call('Page.enable')
await c.call('Emulation.setFocusEmulationEnabled',{enabled:true})
const wait=ms=>new Promise(r=>setTimeout(r,ms))
const read=()=>c.evaluate('({...document.querySelector("output")?.dataset})')
const until=async predicate=>{
  for(let i=0;i<450;i++){const state=await read();if(predicate(state))return state;await wait(25)}
  throw Error('Timeout '+JSON.stringify(await read()))
}
const click=name=>c.evaluate(`[...document.querySelectorAll('button')].find(b=>b.textContent===${JSON.stringify(name)}).click()`)
const toggle=label=>c.evaluate(`document.querySelector('[aria-label="${label}"]').click()`)
const key=code=>c.evaluate(`window.dispatchEvent(new KeyboardEvent('keydown',{code:'${code}',key:'s'}));window.dispatchEvent(new KeyboardEvent('keyup',{code:'${code}',key:'s'}))`)
const records=[]
for(const backend of ['', '?backend=webgl']){
  await c.call('Emulation.setEmulatedMedia',{features:[]})
  await c.call('Emulation.setDeviceMetricsOverride',{width:1440,height:900,deviceScaleFactor:1,mobile:false})
  await c.call('Page.navigate',{url:base+'/lab/game'+backend})
  await until(s=>s.phase==='ready'&&s.started==='false')
  await click('Start')
  await until(s=>s.phase==='running')
  await click('Pause');await wait(250)
  const on=await read()
  assert.equal(on.effects,'true')
  await toggle('Presentation effects');await until(s=>s.effects==='false')
  const off=await read()
  assert.equal(Number(off.drawCalls),Number(on.drawCalls)-1)
  assert.equal(off.activePuffs,'0')
  await toggle('Presentation effects');await until(s=>s.effects==='true')
  await toggle('Environment decorations');await until(s=>s.decorations==='false')
  assert.equal((await read()).effects,'true')
  await toggle('Environment decorations')
  await c.call('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]})
  const reduced=await until(s=>s.reducedMotion==='true'&&s.effects==='false')
  assert.equal(reduced.cameraLead,'2.6')
  assert.equal(await c.evaluate(`document.querySelector('[aria-label="Presentation effects"]').disabled`),true)
  await click('Resume');await wait(350)
  const moved=await read()
  assert.ok(Number(moved.x)>Number(reduced.x))
  assert.ok(Math.abs(Number(moved.cityFarOffset)-Number(reduced.cityFarOffset))<1e-8)
  await click('Test high drop')
  const lowMotionLand=await until(s=>s.animation==='Land')
  assert.equal(lowMotionLand.landEffects,'0');assert.equal(lowMotionLand.activePuffs,'0')
  await until(s=>s.animation==='Run'&&s.recovery==='0')
  await key('KeyS')
  const lowMotionSlide=await until(s=>Number(s.slideTime)>.4)
  assert.equal(lowMotionSlide.animation,'Slide');assert.equal(lowMotionSlide.activePuffs,'0')
  assert.equal(lowMotionSlide.bodyHeight,'0.8')
  await click('Pause');await wait(100)
  const frozen=await read();await wait(150)
  assert.equal((await read()).slideTime,frozen.slideTime)
  await c.call('Emulation.setEmulatedMedia',{features:[]})
  await until(s=>s.effects==='true'&&s.reducedMotion==='false')
  await click('Restart');await wait(100)
  assert.equal((await read()).activePuffs,'0')
  await click('Resume');await click('Test high drop')
  const impact=await until(s=>s.landEffects==='1'&&Number(s.activePuffs)>0)
  const shot=await c.call('Page.captureScreenshot',{format:'png'})
  await writeFile('test-results/g30-impact-'+(backend?'webgl':'webgpu')+'.png',Buffer.from(shot.data,'base64'))
  await toggle('Presentation effects')
  await until(s=>s.effects==='false'&&s.activePuffs==='0')
  await toggle('Presentation effects')
  await until(s=>s.effects==='true')
  assert.equal((await read()).landEffects,'1')
  await click('Restart');await until(s=>s.phase==='ready')
  const failure=await until(s=>s.phase==='fallen')
  assert.equal(failure.failureEffects,'1')
  const opacity=await c.evaluate('Number(document.querySelector(".game-stage").style.getPropertyValue("--impact-opacity"))')
  assert.ok(opacity>0)
  const failShot=await c.call('Page.captureScreenshot',{format:'png'})
  await writeFile('test-results/g30-failure-'+(backend?'webgl':'webgpu')+'.png',Buffer.from(failShot.data,'base64'))
  const count=Number(failure.restarts)+1
  await until(s=>s.phase==='ready'&&Number(s.restarts)===count)
  assert.equal((await read()).activePuffs,'0')
  records.push({backend:backend||'WebGPU',on,off,reduced,lowMotionLand,lowMotionSlide,impact,failure})
}
await click('Test high drop')
await until(s=>s.landEffects==='1'&&Number(s.activePuffs)>0)
await c.call('Page.navigate',{url:base+'/lab/runner'})
await wait(800)
assert.equal(await c.evaluate('!!document.querySelector(".game-stage")'),false)
assert.deepEqual(c.errors,[])
await writeFile('test-results/g30-presentation-browser.json',JSON.stringify(records,null,2))
console.log('Effects toggles, actual events, reduced motion, pause, reset and route cleanup passed')
c.close()
