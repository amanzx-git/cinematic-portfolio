import assert from 'node:assert/strict'
import {writeFile} from 'node:fs/promises'
import {connect} from './cdp.mjs'
const base=process.env.TEST_BASE_URL??'http://127.0.0.1:4175'
const pages=await(await fetch('http://127.0.0.1:9223/json')).json()
const c=await connect(pages.find(p=>p.type==='page').webSocketDebuggerUrl)
await c.call('Runtime.enable');await c.call('Page.enable')
await c.call('Emulation.setFocusEmulationEnabled',{enabled:true})
const wait=ms=>new Promise(r=>setTimeout(r,ms))
const until=async expression=>{for(let i=0;i<300;i++){if(await c.evaluate(expression))return;await wait(40)}throw Error(expression)}
const click=async selector=>{
  const point=await c.evaluate(`(()=>{const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2}})()`)
  await c.call('Input.dispatchMouseEvent',{type:'mousePressed',button:'left',clickCount:1,...point})
  await c.call('Input.dispatchMouseEvent',{type:'mouseReleased',button:'left',clickCount:1,...point})
}
await c.call('Page.navigate',{url:base+'/play'})
await until('!!document.querySelector(".mode-recruiter[href]")')
assert.equal(await c.evaluate('!!document.querySelector(".play-intro-video")'),false)
await click('.sound-control')
await until('document.querySelector("audio").paused===false')
await wait(350)
await c.evaluate('void(window.previousMenuAudio=document.querySelector("audio"))')
await until('document.querySelector(".route-curtain")?.dataset.phase==="idle"')
await click('.mode-recruiter')
assert.equal(await c.evaluate('document.querySelector(".route-curtain").dataset.phase'), 'leaving')
await until('location.pathname==="/play/recruiter"&&!![...document.querySelectorAll("button")].find(b=>b.textContent==="Start")')
await until('document.querySelector("output")?.dataset.started==="false"')
assert.equal(await c.evaluate('document.querySelectorAll("audio").length'),0)
assert.equal(await c.evaluate('window.previousMenuAudio.paused'),true)
assert.equal(await c.evaluate('document.querySelector(".game-debug").hidden'),true)
await until('document.querySelector(".route-curtain")?.dataset.phase==="idle"')
await until('document.activeElement?.textContent==="Start"')
assert.equal(await c.evaluate('Number(document.querySelector("output").dataset.x)'), 0)
assert.equal(await c.evaluate('!!document.querySelector("canvas")'), true)
await click('.game-primary')
await until('document.querySelector("output")?.dataset.started==="true"&&Number(document.querySelector("output").dataset.x)>0')
await click('.game-hud a')
await until('location.pathname==="/play"&&!!document.querySelector(".mode-recruiter")')
assert.equal(await c.evaluate('!!document.querySelector(".play-intro-video")'),false)
assert.equal(await c.evaluate('document.querySelectorAll("audio").length'),1)
await until('document.querySelector("audio").paused===false')
const returnPosition=await c.evaluate('document.querySelector("audio").currentTime')
assert.ok(returnPosition>0)
await until('document.querySelector(".route-curtain")?.dataset.phase==="idle"')
await click('.sound-control')
await until('localStorage.getItem("aman.portfolio.muted")==="true"')
await c.call('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]})
await click('.mode-recruiter')
await until('!!document.querySelector(".game-primary")&&location.pathname==="/play/recruiter"')
await until('document.querySelector(".route-curtain")?.dataset.phase==="idle"')
assert.equal(await c.evaluate('getComputedStyle(document.querySelector(".route-curtain")).transitionDuration'), '0s')
await c.evaluate('history.back()')
await until('location.pathname==="/play"&&!!document.querySelector(".mode-recruiter")')
assert.equal(await c.evaluate('document.querySelector("audio").muted'),true)
assert.equal(await c.evaluate('!!document.querySelector(".play-intro-video")'),false)
await until('document.querySelector(".route-curtain")?.dataset.phase==="idle"')
await c.call('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'no-preference'}]})
await click('.mode-recruiter')
await until('document.querySelector(".route-curtain")?.dataset.phase==="idle"&&location.pathname==="/play/recruiter"')
await c.evaluate('history.back()')
await until('location.pathname==="/play"&&document.querySelector(".route-curtain").dataset.phase==="leaving"')
await c.evaluate('history.forward()')
await until('location.pathname==="/play/recruiter"&&document.querySelector(".route-curtain").dataset.phase==="idle"')
assert.equal(await c.evaluate('document.querySelector("output").dataset.started'), 'false')
await c.call('Page.navigate',{url:base+'/lab/game'})
await until('document.querySelector("output")?.dataset.started==="false"')
assert.equal(await c.evaluate('document.querySelector(".game-hud a").getAttribute("href")'),'/lab')
assert.equal(await c.evaluate('document.querySelector(".game-debug").hidden'),false)
assert.deepEqual(c.errors,[])
await writeFile('test-results/g33-smoke.json',JSON.stringify({passed:true,returnPosition,checks:['modes','recruiter','Start','Back','audio pause/resume','mute','browser Back','lab route','navy curtain','rendered Ready','focus restoration','reduced-motion transition']},null,2))
console.log('G3.3 smoke passed')
c.close()
